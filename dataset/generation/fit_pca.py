"""Fit Block-20 PCA48 on training data only and cache projected sample tensors.

Overview
--------
Performs the same PCA48 procedure as ``visualize_block_20.py`` (random pixel
subsampling over stages 0%, 10%, 20%, randomized low-rank PCA with oversampling,
and deterministic sign canonicalization), but fits the basis exclusively on the
training split generated by ``split_train_and_test.py``.

Every training and test sample's early block-20 feature maps (0%..50%) are then
projected into the frozen training PCA basis and atomically cached as
channels-first ``(48, 48, 48)`` float32 tensors under ``<cache-dir>/Train/`` and
``<cache-dir>/Test/``. Each cached ``.safetensors`` file embeds ``object_class``
and ``target_count`` in its file metadata so downstream loaders stay self-contained.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import torch
from safetensors import safe_open
from safetensors.torch import save_file

from split_train_and_test import read_indexes

try:
    from build_sd3_dataset import EARLY_PERCENTAGES
except ImportError:
    EARLY_PERCENTAGES = (0, 10, 20, 30, 40, 50)


# Stages used to fit the PCA basis (matches visualize_block_20.py).
FIT_PERCENTAGES = (0, 10, 20)


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for train-only PCA fitting and caching."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        type=Path,
        required=True,
        help="Root directory containing raw sample .safetensors and .json files "
             "(searched recursively; works for cell-XX or Train/Test layouts).",
    )
    parser.add_argument(
        "--train-txt",
        type=Path,
        default=Path("train_indexes.txt"),
        help="Path to train_indexes.txt generated by split_train_and_test.py.",
    )
    parser.add_argument(
        "--test-txt",
        type=Path,
        default=Path("test_indexes.txt"),
        help="Path to test_indexes.txt generated by split_train_and_test.py.",
    )
    parser.add_argument(
        "--cache-dir",
        type=Path,
        required=True,
        help="Output directory where Train/, Test/, and PCA basis files will be saved.",
    )
    parser.add_argument(
        "--block",
        type=int,
        default=20,
        help="Transformer block index used in source tensor keys (default: 20).",
    )
    parser.add_argument(
        "--n-components",
        type=int,
        default=48,
        help="Number of principal components to retain (default: 48).",
    )
    parser.add_argument(
        "--fit-pixels-per-map",
        type=int,
        default=128,
        help="Spatial pixels sampled without replacement per training map (default: 128).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for pixel subsampling and randomized PCA (default: 42).",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Recompute and overwrite existing cached sample files.",
    )
    return parser.parse_args()


def discover_sample_files(source_dir: Path, exclude_dir: Path | None = None) -> dict[str, Path]:
    """Recursively index raw sample ``.safetensors`` files by 4-digit sample ID."""
    resolved_exclude = exclude_dir.resolve() if exclude_dir is not None else None
    sample_files: dict[str, Path] = {}

    for path in sorted(source_dir.rglob("*.safetensors")):
        if not path.is_file():
            continue

        # Skip partial temp files, PCA basis artifacts, and anything inside cache_dir.
        if ".partial" in path.name or path.stem.endswith("_basis"):
            continue
        if resolved_exclude is not None and resolved_exclude in path.resolve().parents:
            continue

        sample_id = path.stem
        if sample_id in sample_files:
            raise ValueError(
                f"Duplicate sample ID '{sample_id}' found at both "
                f"{sample_files[sample_id]} and {path}."
            )
        sample_files[sample_id] = path

    return sample_files


def fit_train_pca(
    train_ids: list[str],
    sample_files: dict[str, Path],
    block: int,
    n_components: int,
    fit_pixels_per_map: int,
    seed: int,
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, tuple[int, int, int]]:
    """Fit randomized low-rank PCA strictly on training samples.

    Returns
    -------
    mean : torch.Tensor
        Channel-wise mean vector of shape ``(C,)`` on ``device``.
    components : torch.Tensor
        Sign-canonicalized principal axes of shape ``(C, n_components)`` on ``device``.
    cumulative_variance : torch.Tensor
        Cumulative explained variance ratio of shape ``(n_components,)`` on ``device``.
    feature_shape : tuple[int, int, int]
        Expected source feature map shape ``(C, H, W)``.
    """
    torch.manual_seed(seed)

    fit_parts: list[torch.Tensor] = []
    feature_shape: tuple[int, int, int] | None = None

    for sample_id in sorted(train_ids):
        tensor_path = sample_files[sample_id]
        with safe_open(str(tensor_path), framework="pt", device="cpu") as handle:
            for percent in FIT_PERCENTAGES:
                key = f"block{block:02d}_{percent:03d}"
                feature = handle.get_tensor(key).float().to(device)

                if feature.ndim != 3:
                    raise ValueError(f"Expected 3D tensor for {key} in {tensor_path}, got {tuple(feature.shape)}")

                if feature_shape is None:
                    feature_shape = tuple(feature.shape)
                elif tuple(feature.shape) != feature_shape:
                    raise ValueError(
                        f"Feature shape mismatch in {tensor_path} ({key}): "
                        f"expected {feature_shape}, got {tuple(feature.shape)}"
                    )

                channels = feature_shape[0]
                # Flatten spatial grid: (C, H, W) -> (H * W, C)
                pixels = feature.reshape(channels, -1).T
                if fit_pixels_per_map > pixels.shape[0]:
                    raise ValueError(
                        f"fit_pixels_per_map ({fit_pixels_per_map}) exceeds pixel count ({pixels.shape[0]})."
                    )

                # Subsample distinct spatial locations without replacement.
                selection = torch.randperm(pixels.shape[0], device=device)[:fit_pixels_per_map]
                fit_parts.append(pixels[selection])

    if not fit_parts or feature_shape is None:
        raise RuntimeError("No training feature maps were loaded for PCA fitting.")

    # Concatenate sampled training pixels into design matrix of shape (N_fit, C).
    fit = torch.cat(fit_parts, dim=0)
    del fit_parts

    mean = fit.mean(dim=0)
    print(
        f"Fitting PCA{n_components} on {len(train_ids)} training samples: "
        f"{fit.shape[0]} pixels x {feature_shape[0]} channels on {device}",
        flush=True,
    )

    # Oversample subspace dimension q = n_components + 8 (q=56 for 48 PCs) with 3 power iterations.
    oversampled_q = min(n_components + 8, fit.shape[0], fit.shape[1])
    _, singular_values, components = torch.pca_lowrank(
        fit,
        q=oversampled_q,
        center=True,
        niter=3,
    )
    components = components[:, :n_components].contiguous()

    # Resolve SVD sign ambiguity: largest-magnitude loading on each axis is positive.
    for axis in range(n_components):
        anchor = components[:, axis].abs().argmax()
        if components[anchor, axis] < 0:
            components[:, axis] *= -1

    # Total centered squared Frobenius norm without allocating a second full (N_fit, C) copy.
    total_variance = fit.var(dim=0, unbiased=False).sum() * fit.shape[0]
    cumulative_variance = (singular_values[:n_components] ** 2).cumsum(0) / total_variance
    del fit

    return mean, components, cumulative_variance, feature_shape


def load_sample_provenance(tensor_path: Path) -> dict[str, str]:
    """Read ``object_class`` and ``target_count`` from the sample's sibling JSON."""
    meta_path = tensor_path.with_suffix(".json")
    if not meta_path.is_file():
        raise FileNotFoundError(
            f"Missing sibling metadata JSON for {tensor_path.name}: expected {meta_path}"
        )

    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    if "object_class" not in meta or "target_count" not in meta:
        raise ValueError(f"Metadata JSON {meta_path} must contain 'object_class' and 'target_count'.")

    return {
        "object_class": str(meta["object_class"]),
        "target_count": str(int(meta["target_count"])),
    }


def project_and_cache_split(
    split_name: str,
    sample_ids: list[str],
    sample_files: dict[str, Path],
    output_dir: Path,
    mean: torch.Tensor,
    components: torch.Tensor,
    feature_shape: tuple[int, int, int],
    block: int,
    overwrite: bool,
    device: torch.device,
) -> None:
    """Project every sample in a split using the frozen training PCA basis and save atomically."""
    output_dir.mkdir(parents=True, exist_ok=True)
    channels, height, width = feature_shape
    n_components = components.shape[1]

    for position, sample_id in enumerate(sorted(sample_ids), start=1):
        target_path = output_dir / f"{sample_id}.safetensors"
        if target_path.is_file() and not overwrite:
            continue

        source_path = sample_files[sample_id]
        provenance = load_sample_provenance(source_path)

        pca_tensors: dict[str, torch.Tensor] = {}
        with safe_open(str(source_path), framework="pt", device="cpu") as handle:
            for percent in EARLY_PERCENTAGES:
                source_key = f"block{block:02d}_{percent:03d}"
                feature = handle.get_tensor(source_key).float().to(device)
                if tuple(feature.shape) != feature_shape:
                    raise ValueError(
                        f"Shape mismatch in {source_path} ({source_key}): "
                        f"expected {feature_shape}, got {tuple(feature.shape)}"
                    )

                # Project (C, H, W) -> (H*W, C) -> (H*W, K) -> channels-first (K, H, W).
                pixels = feature.reshape(channels, -1).T
                scores = (pixels - mean) @ components
                pca_map = scores.T.reshape(n_components, height, width)

                if not torch.isfinite(pca_map).all():
                    raise RuntimeError(f"Non-finite PCA values computed for {sample_id} ({source_key}).")

                pca_tensors[f"pca_{percent:03d}"] = pca_map.detach().cpu().contiguous()

        # Store sample metadata directly in the safetensors header and write atomically.
        file_metadata = {
            "id": sample_id,
            "split": split_name,
            "object_class": provenance["object_class"],
            "target_count": provenance["target_count"],
        }
        tmp_path = output_dir / f"{sample_id}.partial.safetensors"
        save_file(pca_tensors, str(tmp_path), metadata=file_metadata)
        os.replace(tmp_path, target_path)

        if position % 50 == 0 or position == len(sample_ids):
            print(f"[{split_name}] cached {position}/{len(sample_ids)} samples", flush=True)


def save_pca_basis(
    cache_dir: Path,
    mean: torch.Tensor,
    components: torch.Tensor,
    cumulative_variance: torch.Tensor,
    train_ids: list[str],
    test_ids: list[str],
    args: argparse.Namespace,
) -> None:
    """Save the fitted training PCA basis tensors and provenance JSON atomically."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    n_components = components.shape[1]

    basis_path = cache_dir / f"pca{n_components}_basis.safetensors"
    basis_tmp = cache_dir / f"pca{n_components}_basis.partial.safetensors"
    save_file(
        {
            "mean": mean.detach().cpu().contiguous(),
            "components": components.detach().cpu().contiguous(),
        },
        str(basis_tmp),
    )
    os.replace(basis_tmp, basis_path)

    cutoffs = range(3, n_components + 1, 3)
    basis_meta = {
        "feature_block": args.block,
        "components_kept": n_components,
        "fit_percentages": list(FIT_PERCENTAGES),
        "cached_percentages": list(EARLY_PERCENTAGES),
        "fit_pixels_per_map": args.fit_pixels_per_map,
        "random_seed": args.seed,
        "train_count": len(train_ids),
        "test_count": len(test_ids),
        "train_ids": sorted(train_ids),
        "test_ids": sorted(test_ids),
        "explained_variance_first_3": float(cumulative_variance[min(2, n_components - 1)]),
        "explained_variance_all": float(cumulative_variance[-1]),
        "cumulative_explained_variance": {
            str(k): float(cumulative_variance[k - 1]) for k in cutoffs
        },
        "tensor_layout": "channels-first (n_components, H, W), float32",
    }

    meta_path = cache_dir / f"pca{n_components}_basis.json"
    meta_tmp = cache_dir / f"pca{n_components}_basis.partial.json"
    meta_tmp.write_text(json.dumps(basis_meta, indent=2) + "\n", encoding="utf-8")
    os.replace(meta_tmp, meta_path)
    print(
        f"Saved PCA basis to {basis_path} "
        f"(explained variance: top-3={basis_meta['explained_variance_first_3']:.1%}, "
        f"top-{n_components}={basis_meta['explained_variance_all']:.1%})",
        flush=True,
    )


def main() -> None:
    args = parse_args()

    # 1. Load train/test split and verify zero overlap (prevents any test leakage into PCA).
    train_ids, test_ids = read_indexes(args.train_txt, args.test_txt)
    overlap = set(train_ids) & set(test_ids)
    if overlap:
        raise RuntimeError(f"Train and test splits overlap on IDs: {sorted(overlap)[:10]}")

    # 2. Locate all raw sample files and verify completeness.
    sample_files = discover_sample_files(args.source_dir, exclude_dir=args.cache_dir)
    missing_train = sorted(set(train_ids) - set(sample_files))
    missing_test = sorted(set(test_ids) - set(sample_files))
    if missing_train or missing_test:
        raise FileNotFoundError(
            f"Missing raw .safetensors files (train missing: {len(missing_train)}, "
            f"test missing: {len(missing_test)}). Examples: {(missing_train + missing_test)[:5]}"
        )

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # 3. Fit PCA strictly on the training split.
    mean, components, cumulative_variance, feature_shape = fit_train_pca(
        train_ids=train_ids,
        sample_files=sample_files,
        block=args.block,
        n_components=args.n_components,
        fit_pixels_per_map=args.fit_pixels_per_map,
        seed=args.seed,
        device=device,
    )

    # 4. Save the fitted basis and cache projected tensors for Train and Test.
    save_pca_basis(
        cache_dir=args.cache_dir,
        mean=mean,
        components=components,
        cumulative_variance=cumulative_variance,
        train_ids=train_ids,
        test_ids=test_ids,
        args=args,
    )

    project_and_cache_split(
        split_name="Train",
        sample_ids=train_ids,
        sample_files=sample_files,
        output_dir=args.cache_dir / "Train",
        mean=mean,
        components=components,
        feature_shape=feature_shape,
        block=args.block,
        overwrite=args.overwrite,
        device=device,
    )
    project_and_cache_split(
        split_name="Test",
        sample_ids=test_ids,
        sample_files=sample_files,
        output_dir=args.cache_dir / "Test",
        mean=mean,
        components=components,
        feature_shape=feature_shape,
        block=args.block,
        overwrite=args.overwrite,
        device=device,
    )


if __name__ == "__main__":
    main()